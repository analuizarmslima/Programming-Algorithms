print("4. FATIAMENTO DE TUPLAS:\n")

tupla = ("a", "n", "a", "l", "u", "i", "z", "a")
print(f"Tupla: {tupla}\n")

print(f"tupla[2:5]: {tupla[2:5]}")
print(f"tupla[:3]: {tupla[:3]}")
print(f"tupla[6:]: {tupla[6:]}")
print(f"tupla[::2]: {tupla[::2]}")
print(f"tupla[::-1]: {tupla[::-1]}\n")

print("="*60 + "\n")